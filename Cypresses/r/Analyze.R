# Открываем файл out.txt (он будет создан в вашей рабочей папке)
# split = TRUE означает, что вывод будет идти И в файл, И на экран (очень удобно!)
# Если хотите, чтобы вывод шел ТОЛЬКО в файл, уберите split = TRUE
sink("Cypresses/_Output.txt", split = FALSE)

# Фиксируем генератор случайных чисел (чтобы результат перестановок всегда был одинаковым)
set.seed(1234)

# 2.1 Загрузка данных
# check.names = FALSE важно, чтобы R не испортил названия TAG (не заменил скобки на точки)
mydata <- read.csv("Cypresses/_Wide.txt", check.names = FALSE)

# Отделяем матрицу обилий (начиная с 7-го столбца)
abund <- mydata[, 7:ncol(mydata)]
m_abund <- as.matrix(abund)
group_factor <- mydata$Variety

# ---------------------------------------------------------------------
# 2.2 Тест ANOSIM (Анализ сходства)
# ---------------------------------------------------------------------
cat("=== Результаты ANOSIM ===\n")
ano <- anosim(m_abund, group_factor, distance = "bray", permutations = 9999)
print(summary(ano))

# ---------------------------------------------------------------------
# 2.3 Тест PERMANOVA (Многофакторный дисперсионный анализ)
# ---------------------------------------------------------------------
cat("\n=== Результаты PERMANOVA ===\n")
# Примечание: в новых версиях vegan функция adonis() заменена на adonis2()
perm <- adonis2(m_abund ~ Variety, data = mydata, permutations = 999, method = "bray")
print(perm)

# ---------------------------------------------------------------------
# 2.4 Ординация NMDS (Неметрическое многомерное шкалирование)
# ---------------------------------------------------------------------
# Вычисляем NMDS
nmds <- metaMDS(m_abund, distance = "bray", k = 2, autotransform = FALSE)

# Визуализация (как на Рис. 3 и 5 в статье)
plot(nmds, type = "n", main = "NMDS Ordination of TAGs")
# Добавляем точки образцов
points(nmds, display = "sites", pch = 16, col = as.numeric(as.factor(group_factor)))
# Выделяем области (эллипсы/многоугольники) для групп
ordihull(nmds, groups = group_factor, label = TRUE, col = c("blue", "red"))
# При желании можно добавить виды (TAGs) на график:
# points(nmds, display = "species", pch = "+", col = "grey")

# ---------------------------------------------------------------------
# 2.5 Процедура IndVal (Виды-индикаторы)
# ---------------------------------------------------------------------
cat("\n=== Результаты IndVal ===\n")
inv <- multipatt(m_abund, group_factor, func = "r.g", control = how(nperm=999))
inv_sum <- summary(inv)
print(inv_sum)

# ---------------------------------------------------------------------
# 2.6 Процедура SIMPER (Оценка вклада видов в различия)
# ---------------------------------------------------------------------
cat("\n=== Результаты SIMPER ===\n")
sim <- simper(m_abund, group_factor)
# print(sim_sum)
sim_sum <- summary(sim)
for (comp_name in names(sim_sum)) {
  cat("\n--------------------------------------------------\n")
  cat("Сравнение:", comp_name, "\n")
  cat("--------------------------------------------------\n")
  
  df <- sim_sum[[comp_name]]
  
  # Округляем длинные числа до 4 знаков после запятой для красоты
  is_num <- sapply(df, is.numeric)
  df[is_num] <- lapply(df[is_num], round, 4)
  
  # Выводим красивую таблицу (формат markdown)
  print(kable(df, format = "markdown"))
  cat("\n")
}

# =====================================================================
# КОНЕЦ ПЕРЕНАПРАВЛЕНИЯ ВЫВОДА
# =====================================================================
# Закрываем файл
sink()