import pandas as pd
import matplotlib.pyplot as plt
from scipy.cluster.hierarchy import dendrogram, linkage
import seaborn as sns

# 1. Подготавливаем данные
data = {
    'Пик 1': [4.2, 3.68, 1.43],
    'Пик 2': [0.61, 1.47, 0.4],
    'Пик 3': [5.02, 0.89, 4.43],
    'Пик 4': [18.21, 9.35, 5.79],
    'Пик 5': [1.75, 2.05, 11.81],
    'Пик 6': [0.44, 0.0, 1.19],
    'Пик 7': [0.0, 0.0, 1.26],
    'Пик 8': [0.63, 0.0, 0.51],
    'Пик 9': [6.48, 12.17, 0.52],
    'Пик 10': [38.96, 33.22, 41.43],
    'Пик 11': [1.81, 0.36, 16.37],
    'Пик 12': [0.0, 0.42, 0.0],
    'Пик 13': [6.02, 33.96, 1.46],
    'Пик 14': [12.84, 1.53, 11.93],
    'Triolein': [6.79, 5.28, 4.71],
    'Пик 15': [0.0, 0.54, 0.0],
    'Пик 16': [0.54, 0.0, 0.0]
}

# Названия образцов (строки)
index = ['B', 'C-70', 'H-150']

# Создаем DataFrame
df = pd.DataFrame(data, index=index)

# 2. Вычисляем матрицу связей (linkage matrix)
# Используем метод Уорда (ward), который минимизирует дисперсию внутри кластеров
# Метрика расстояния - евклидова
Z = linkage(df, method='ward', metric='euclidean')

# 3. Строим классическую дендрограмму
plt.figure(figsize=(8, 5))
plt.title('Иерархическое дерево (Дендрограмма) образцов')
plt.xlabel('Образцы')
plt.ylabel('Евклидово расстояние')

dendrogram(
    Z,
    labels=df.index,
    leaf_rotation=0,  # Угол поворота подписей
    leaf_font_size=14, # Размер шрифта
    color_threshold=0  # Чтобы все ветви были одного цвета (можно изменить для выделения кластеров)
)

plt.grid(axis='y', linestyle='--', alpha=0.7)
plt.tight_layout()
plt.show()

# ==========================================
# БОНУС: Тепловая карта с дендрограммой (Clustermap)
# ==========================================
# Это очень популярный способ в химии и биологии, 
# так как он показывает не только дерево, но и из-за каких именно пиков образцы похожи/различаются.

sns.clustermap(
    df, 
    method='average', 
    # metric='euclidean', 
    metric='braycurtis', 
    cmap='Reds', # Цветовая палитра (от желтого к синему)
    # standard_scale=1,
    figsize=(12, 6),
    col_cluster=True, # Отключаем кластеризацию самих пиков (оставляем только для образцов)
    annot=True,        # Показывать значения в ячейках
    fmt=".1f"          # Формат чисел (1 знак после запятой)
)
plt.title('Тепловая карта с иерархическим деревом', pad=20)
plt.show()