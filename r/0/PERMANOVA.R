library(vegan)
library(indicspecies)

# Загружаем встроенные тестовые данные
data(dune)      # Матрица: строки - участки, столбцы - обилие видов
data(dune.env)  # Данные о среде, включая тип использования (Management)

# 3. Фиксируем генератор случайных чисел (чтобы результат перестановок всегда был одинаковым)
set.seed(123)

abund <- dune                # Матрица обилия видов
habitat <- dune.env$Management # Наш фактор (группы/местообитания)

# Выполняем PERMANOVA с расстоянием Брея-Кертиса (bray)
perm_result <- adonis2(abund ~ habitat, method = "bray", permutations = 999)
print(perm_result)

# Результаты:
# - R2 (R-squared): показывает долю вариации (дисперсии) видового состава, которая объясняется различиями между нашими биотопами. Например, R2 = 0.34 означает, что 34% различий объясняется типом местообитания.
# - Pr(>F) (p-value): уровень значимости. Если он меньше 0.05 (например, 0.001), мы делаем вывод: видовой состав в разных местообитаниях достоверно различается.