# R-статистика (ANOSIM statistic R): варьирует от 0 до 1.
# - R = 1: группы полностью различаются (нет пересечений).
# - R = 0: группы абсолютно идентичны.
# - Согласно автору статьи, R > 0.75 — хорошие различия, R > 0.5 — различия есть, R < 0.25 — едва различимы.
# Significance (p-value): Если < 0.05, то различия статистически достоверны.

library(vegan)
library(indicspecies)

# Загружаем встроенные тестовые данные
data(dune)      # Матрица: строки - участки, столбцы - обилие видов
data(dune.env)  # Данные о среде, включая тип использования (Management)

# 3. Фиксируем генератор случайных чисел (чтобы результат перестановок всегда был одинаковым)
set.seed(123)

abund <- dune                # Матрица обилия видов
habitat <- dune.env$Management # Наш фактор (группы/местообитания)

# Выполняем ANOSIM с расстоянием Брея-Кертиса (bray)
ano <- anosim(abund, habitat, distance = "bray", permutations = 9999)
summary(ano)
