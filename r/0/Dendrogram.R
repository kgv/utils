# =====================================================================
# ГРАФИК 2: ТЕПЛОВАЯ КАРТА (HEATMAP)
# =====================================================================

# Создаем таблицу аннотаций для раскраски групп над графиком
annotation_col <- data.frame(Group = group_factor)
# Имена строк в аннотации должны строго совпадать с именами образцов!
rownames(annotation_col) <- sample_names

# Строим тепловую карту
# t(m_abund_clean) - транспонируем матрицу, чтобы образцы были по горизонтали, а липиды по вертикали
pheatmap(t(m_abund_clean), 
         clustering_distance_cols = "correlation", # Метод кластеризации колонок (образцов)
         clustering_distance_rows = "correlation", # Метод кластеризации строк (липидов)
         scale = "row",                            # Стандартизация по строкам (показывает относительное обилие)
         annotation_col = annotation_col,          # Добавляем цветную полоску групп
         fontsize_row = 6,                         # Размер шрифта для названий липидов (уменьшен)
         fontsize_col = 9,                         # Размер шрифта для названий образцов
         main = "Тепловая карта липидного профиля",
         filename = "heatmap_lipids.png",  # Имя файла и расширение
         width = 10,                       # Ширина в дюймах
         height = 8)                       # Высота в дюймах
