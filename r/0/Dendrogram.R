# 1. Загрузка необходимых библиотек
library(vegan)
library(pheatmap)

# 2. Чтение данных
# check.names = FALSE нужен, чтобы R не заменял скобки и спецсимволы в названиях липидов на точки
# Если ваш файл разделен точкой с запятой, добавьте sep = ";"
mydata <- read.csv("data.csv", check.names = FALSE)

# 3. Подготовка данных
# Предполагается, что:
# 1-й столбец - названия образцов (Sample)
# 2-й столбец - названия групп (Group)
# с 3-го столбца и далее - количественные данные (липиды)

sample_names <- mydata[, 1]       # Извлекаем имена образцов
group_factor <- mydata[, 2]       # Извлекаем группы (или mydata$Group)

# Создаем числовую матрицу
abund <- mydata[, 3:ncol(mydata)]
m_abund <- as.matrix(abund)

# ВАЖНО: Назначаем матрице имена строк (решает ошибку "subscript out of bounds")
rownames(m_abund) <- sample_names

# 4. Очистка данных от "нулевых" липидов
# Находим липиды, у которых дисперсия (разброс) больше 0
# Это уберет липиды, которых нет ни в одном образце, и решит проблему с 50+ warnings
valid_lipids <- apply(m_abund, 2, var) > 0
m_abund_clean <- m_abund[, valid_lipids]

# =====================================================================
# ГРАФИК 1: ИЕРАРХИЧЕСКАЯ КЛАСТЕРИЗАЦИЯ (ДЕНДРОГРАММА)
# =====================================================================

# bray
# euclidean
# hellinger
# Считаем матрицу расстояний методом Брея-Кертиса (как в вашей статье)
dist_matrix <- vegdist(m_abund_clean, method = "bray")

# Строим дерево кластеризации (метод средних связей)
hc <- hclust(dist_matrix, method = "average")

